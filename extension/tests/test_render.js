'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const ctx={window:{},TextEncoder,Blob,Uint8Array,ArrayBuffer,atob,Date};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','render.js'),'utf8'),ctx);
const r=ctx.window.NormLocalRender;
const sample=['| Col | Value |','| --- | --- |','| one | **two** |','','[Source](https://example.org/path)','','- [x] done','- [ ] todo','','---','','`*literal*`'].join('\n');
const data={title:'Render test',source:'chatgpt-api-graph',coverage:'test',messages:[{role:'assistant',text:sample}]};
const html=r.buildHtml(data);
assert.match(html,/<table><thead>/);
assert.match(html,/<td><strong>two<\/strong><\/td>/);
assert.match(html,/href="https:\/\/example.org\/path"/);
assert.match(html,/<li>☑ done<\/li>/);
assert.match(html,/<li>☐ todo<\/li>/);
assert.match(html,/<hr>/);
assert.match(html,/<code>\*literal\*<\/code>/);
assert.match(r.buildMarkdown(data),/\| Col \| Value \|/);
console.log('PASS: table, link, checklist, separator, code, Markdown');
